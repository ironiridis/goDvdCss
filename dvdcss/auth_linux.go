func cryptKey(keyType, variant int, challenge [10]byte) Key {
	permChallenge := [3][10]byte{
		{1, 3, 0, 7, 5, 2, 9, 6, 4, 8},
		{6, 1, 9, 3, 8, 5, 7, 4, 0, 2},
		{4, 0, 3, 5, 7, 2, 8, 6, 1, 9},
	}
	permVariant := [2][32]byte{
		{0x0a, 0x08, 0x0e, 0x0c, 0x0b, 0x09, 0x0f, 0x0d, 0x1a, 0x18, 0x1e, 0x1c, 0x1b, 0x19, 0x1f, 0x1d, 0x02, 0x00, 0x06, 0x04, 0x03, 0x01, 0x07, 0x05, 0x12, 0x10, 0x16, 0x14, 0x13, 0x11, 0x17, 0x15},
		{0x12, 0x1a, 0x16, 0x1e, 0x02, 0x0a, 0x06, 0x0e, 0x10, 0x18, 0x14, 0x1c, 0x00, 0x08, 0x04, 0x0c, 0x13, 0x1b, 0x17, 0x1f, 0x03, 0x0b, 0x07, 0x0f, 0x11, 0x19, 0x15, 0x1d, 0x01, 0x09, 0x05, 0x0d},
	}
	variants := [32]byte{0xb7, 0x74, 0x85, 0xd0, 0xcc, 0xdb, 0xca, 0x73, 0x03, 0xfe, 0x31, 0x03, 0x52, 0xe0, 0xb7, 0x42, 0x63, 0x16, 0xf2, 0x2a, 0x79, 0x52, 0xff, 0x1b, 0x7a, 0x11, 0xca, 0x1a, 0x9b, 0x40, 0xad, 0x01}
	secret := [5]byte{0x55, 0xd6, 0xc4, 0xc5, 0x28}
	var scratch, bits [30]byte
	var tmp1, tmp2 [5]byte
	for i := 9; i >= 0; i-- {
		scratch[i] = challenge[permChallenge[keyType][i]]
	}
	cssVariant := byte(variant)
	if keyType != 0 {
		cssVariant = permVariant[keyType-1][variant]
	}
	for i := 5; i > 0; i-- {
		j := i - 1
		tmp1[j] = scratch[5+j] ^ secret[j] ^ cryptTab2[j]
	}
	lfsr0 := uint32(tmp1[0])<<17 | uint32(tmp1[1])<<9 | uint32(tmp1[2]&^7)<<1 | 8 | uint32(tmp1[2]&7)
	lfsr1 := uint32(tmp1[3])<<9 | 0x100 | uint32(tmp1[4])
	index := 30
	carry := byte(0)
	for index > 0 {
		value := byte(0)
		for bit := 0; bit < 8; bit++ {
			out0 := byte((lfsr0>>24 ^ lfsr0>>21 ^ lfsr0>>20 ^ lfsr0>>12) & 1)
			lfsr0 = lfsr0<<1 | uint32(out0)
			out1 := byte((lfsr1>>16 ^ lfsr1>>2) & 1)
			lfsr1 = lfsr1<<1 | uint32(out1)
			combined := (out1 ^ 1) + carry + (out0 ^ 1)
			carry = (combined >> 1) & 1
			value |= (combined & 1) << bit
		}
		index--
		bits[index] = value
	}
	cse := variants[cssVariant] ^ cryptTab2[cssVariant]
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[25+i] ^ scratch[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		tmp1[i] = cryptTab2[index] ^ cryptTab3[index] ^ term
		term = scratch[i]
	}
	tmp1[4] ^= tmp1[0]
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[20+i] ^ tmp1[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		tmp2[i] = cryptTab2[index] ^ cryptTab3[index] ^ term
		term = tmp1[i]
	}
	tmp2[4] ^= tmp2[0]
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[15+i] ^ tmp2[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		index = cryptTab2[index] ^ cryptTab3[index] ^ term
		tmp1[i] = cryptTab0[index] ^ cryptTab2[index]
		term = tmp2[i]
	}
	tmp1[4] ^= tmp1[0]
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[10+i] ^ tmp1[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		index = cryptTab2[index] ^ cryptTab3[index] ^ term
		tmp2[i] = cryptTab0[index] ^ cryptTab2[index]
		term = tmp1[i]
	}
	tmp2[4] ^= tmp2[0]
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[5+i] ^ tmp2[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		tmp1[i] = cryptTab2[index] ^ cryptTab3[index] ^ term
		term = tmp2[i]
	}
	tmp1[4] ^= tmp1[0]
	var result Key
	for i, term := 4, byte(0); i >= 0; i-- {
		index := bits[i] ^ tmp1[i]
		index = cryptTab1[index] ^ ^cryptTab2[index] ^ cse
		result[i] = cryptTab2[index] ^ cryptTab3[index] ^ term
		term = tmp1[i]
	}
	return result
}

func authenticate(fd uintptr) (int, Key, error) {
	agid, err := reportAgid(fd, 0)
	for i := 0; err != nil && i < 4; i++ {
		agid = i
		_ = invalidateAGID(fd, agid)
		agid, err = reportAgid(fd, agid)
	}
	if err != nil {
		return 0, Key{}, errAuthentication
	}
	var challenge [10]byte
	for i := range challenge {
		challenge[i] = byte(i)
	}
	var reversed [10]byte
	for i := range reversed {
		reversed[9-i] = challenge[i]
	}
	if err = sendChallenge(fd, agid, reversed); err != nil {
		_ = invalidateAGID(fd, agid)
		return 0, Key{}, errAuthentication
	}
	reportedKey, err := reportKey1(fd, agid)
	if err != nil {
		_ = invalidateAGID(fd, agid)
		return 0, Key{}, errAuthentication
	}
	var key1 Key
	for i := range key1 {
		key1[i] = reportedKey[4-i]
	}
	variant := -1
	for i := 0; i < 32; i++ {
		if cryptKey(0, i, challenge) == key1 {
			variant = i
			break
		}
	}
	if variant < 0 {
		_ = invalidateAGID(fd, agid)
		return 0, Key{}, errAuthentication
	}
	reportedChallenge, err := reportChallenge(fd, agid)
	if err != nil {
		_ = invalidateAGID(fd, agid)
		return 0, Key{}, errAuthentication
	}
	for i := range challenge {
		challenge[i] = reportedChallenge[9-i]
	}
	key2 := cryptKey(1, variant, challenge)
	var sentKey2 Key
	for i := range sentKey2 {
		sentKey2[4-i] = key2[i]
	}
	if err = sendKey2(fd, agid, sentKey2); err != nil {
		_ = invalidateAGID(fd, agid)
		return 0, Key{}, errAuthentication
	}
	var busInput [10]byte
	copy(busInput[:5], key1[:])
	copy(busInput[5:], key2[:])
	return agid, cryptKey(2, variant, busInput), nil
}

func (dvd *DVD) loadDiscKey() error {
	if dvd.discKnown {
		return nil
	}
	if dvd.fd == nil {
		return errAuthentication
	}
	agid, busKey, err := authenticate(*dvd.fd)
	if err != nil {
		return err
	}
	encrypted, err := readDiscKey(*dvd.fd, agid)
	if err != nil {
		return err
	}
	asf, err := reportASF(*dvd.fd)
	if err != nil || asf != 1 {
		_ = invalidateAGID(*dvd.fd, agid)
		return errAuthentication
	}
	for i := range encrypted {
		encrypted[i] ^= busKey[4-(i%KeySize)]
	}
	discKey, err := decryptDiscKey(encrypted)
	if err != nil {
		return err
	}
	dvd.agid, dvd.busKey, dvd.discKey, dvd.discKnown = agid, busKey, discKey, true
	return nil
}

